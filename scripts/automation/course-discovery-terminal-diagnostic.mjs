const phases = new Set(["GENERIC_FALLBACK", "STAGEHAND", "WORKER"]);
const names = new Set(["Error", "TypeError", "RangeError", "SyntaxError", "TimeoutError", "AbortError", "ZodError", "ProtocolError", "UNKNOWN"]);
const record = value => value && typeof value === "object" && !Array.isArray(value) ? value : {};
export function makeWorkerTerminalDiagnostic(error) {
  const input = record(error), metrics = record(input.discoveryMetrics);
  return { version: 1, failureCode: codes.has(input.code) ? input.code : "UNKNOWN_WORKER_FAILURE",
    frameworkPhase: Object.keys(record(metrics.genericFallback)).length ? "GENERIC_FALLBACK" : metrics.framework === "Stagehand" ? "STAGEHAND" : "WORKER",
    errorName: names.has(input.name) ? input.name : "UNKNOWN" };
}
export function parseWorkerTerminalDiagnostic(value) {
  const input = record(value);
  if (Object.keys(input).sort().join(",") !== "errorName,failureCode,frameworkPhase,version" || input.version !== 1 ||
      !codes.has(input.failureCode) || !phases.has(input.frameworkPhase) || !names.has(input.errorName)) return;
  return { version: 1, failureCode: input.failureCode, frameworkPhase: input.frameworkPhase, errorName: input.errorName };
}
